NOW2 = datetime(2026, 9, 27, 21, 30)
def chk(text, shop, st, shifts, tent=(), now=None):
    global ok
    r = read_shift_reply(text, now or NOW2, shop)
    if r["status"] != st or r["shifts"] != shifts or r["tentative"] != sorted(tent):
        ok = False
        print(f"✗ {text[:30]!r} → {r}")
