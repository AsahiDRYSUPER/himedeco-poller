"""shift_reply の判定が、一希さんと決めたパターンどおりかを確かめる（ネット不要）。"""
from datetime import date, datetime

from shift_reply import read_shift_reply, hhmm

NOW = datetime(2026, 9, 24, 23, 0)          # 9/24 23:00 として読む

CLEAR = {
    "26日 12-20時 / 27日 10-17時": [(date(2026, 9, 26), "12:00", "20:00"), (date(2026, 9, 27), "10:00", "17:00")],
    "お疲れ様です。 / 26日17時〜22時半でお願いします🙇‍♀️": [(date(2026, 9, 26), "17:00", "22:30")],
    "27日 14時〜21時 / お願いします🙇‍♀️": [(date(2026, 9, 27), "14:00", "21:00")],
    "27日21時30から24時30 出勤お願いします！": [(date(2026, 9, 27), "21:30", "24:30")],
    "26日 12:00〜20:00": [(date(2026, 9, 26), "12:00", "20:00")],
    "9/26 12〜20時でお願いします": [(date(2026, 9, 26), "12:00", "20:00")],
    "10月1日 12時から20時まで": [(date(2026, 10, 1), "12:00", "20:00")],
    "２６日　１２時ー２０時": [(date(2026, 9, 26), "12:00", "20:00")],
    "26日と27日 12時〜20時": [(date(2026, 9, 26), "12:00", "20:00"), (date(2026, 9, 27), "12:00", "20:00")],
    "明日 12〜20時出れます": [(date(2026, 9, 25), "12:00", "20:00")],
    "1日 12〜20時": [(date(2026, 10, 1), "12:00", "20:00")],
    "26日 22時〜2時": [(date(2026, 9, 26), "22:00", "26:00")],
    "26日 12時00分〜20時00分": [(date(2026, 9, 26), "12:00", "20:00")],
}
UNCLEAR = [
    "26日12〜15時だけでもいいですか",
    "26日 12〜20時かな",
    "26日",
    "26日 12時から",
    "26日 12時〜ラスト",
    "26日 12〜20時くらい",
    "26日 12〜20時かも",
    "26日か27日 12〜20時",
    "26日 12〜15時か18〜21時",
    "26日 12〜20時 27日も",
    "26〜28日 12〜20時",
    "26日 休みます",
    "12〜20時でお願いします",
    "26日 12:15〜20:00",
    "26日 12〜13時半 で、27日は体調次第で",
    "26日 12〜20時、当日キャンセルになるかもです",
    "土曜 12〜20時",
    "26日 12〜20時 予約あれば",
    "26日 12〜20時で大丈夫ですか？",
    "24日 12〜20時",                    # 今日の、もう始まっている時間
    "26日 10〜29時",                    # 長すぎ
    "11/30 12〜20時",                   # 先すぎ
]
NONE = ["ありがとうございます！", "了解です", "いろいろすいません", "裏姫デコほしいです",
        "とどにち土日出勤するかいま悩んでて🥲🥲",                      # 数字が無い → ふつうの連絡として通知
        "当日休むっていうのが怖いので当日に言うのでも大丈夫ですか、？"]

ok = True
for text, want in CLEAR.items():
    r = read_shift_reply(text, NOW)
    if want is None:
        continue
    if r["status"] != "clear" or r["shifts"] != want:
        ok = False
        print(f"✗ clear のはず: {text!r} → {r}")
for text in UNCLEAR:
    r = read_shift_reply(text, NOW)
    if r["status"] != "unclear":
        ok = False
        print(f"✗ unclear のはず: {text!r} → {r}")
for text in NONE:
    r = read_shift_reply(text, NOW)
    if r["status"] != "none":
        ok = False
        print(f"✗ none のはず: {text!r} → {r}")
assert hhmm("24:30") == "0030" and hhmm("26:00") == "0200" and hhmm("12:00") == "1200"
r = read_shift_reply("26日 12-20時 / 27日 10-17時", NOW)
assert r["hint"] == "26日 12:00〜20:00 / 27日 10:00〜17:00", r["hint"]
r = read_shift_reply("26日 12時から", NOW)
assert r["hint"] == "日にちはあるが時間が読めない", r
print("すべて通りました" if ok else "直すところがあります")
raise SystemExit(0 if ok else 1)
