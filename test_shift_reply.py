ok = True
for text, want in CLEAR.items():
    r = read_shift_reply(text, NOW)
    if want is None:
        continue
    if r["status"] != "clear" or r["shifts"] != want:
        ok = False
        print(f"✗ clear のはず: {text!r} → {r}")
for text in UNCLEAR:
    r = read_shift_reply(text, NOW)
    if r["status"] != "unclear":
        ok = False
        print(f"✗ unclear のはず: {text!r} → {r}")
for text in NONE:
    r = read_shift_reply(text, NOW)
    if r["status"] != "none":
        ok = False
        print(f"✗ none のはず: {text!r} → {r}")
